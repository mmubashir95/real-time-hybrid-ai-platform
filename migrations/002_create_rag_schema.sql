-- Create the approved Phase 6.2 storage contract; never import corpus data.
-- Apply with psql -v ON_ERROR_STOP=1. One DO statement is atomic and also works
-- through asyncpg; the completion ledger makes successful reapplication a no-op.
DO $migration$
DECLARE
    target_schema TEXT := current_schema();
    object_name TEXT;
BEGIN
    IF current_setting('server_version_num')::INTEGER NOT BETWEEN 170000 AND 179999 THEN
        RAISE EXCEPTION 'RAG schema requires PostgreSQL 17';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pg_extension e JOIN pg_namespace n ON n.oid = e.extnamespace
        WHERE e.extname = 'vector' AND n.nspname = 'public'
    ) THEN
        RAISE EXCEPTION 'Enable pgvector in public in this database using migrations/001_enable_pgvector.sql first';
    END IF;
    IF target_schema IS NULL OR target_schema LIKE 'pg_%' THEN
        RAISE EXCEPTION 'Select a writable application schema before applying the RAG migration';
    END IF;

    -- Keep installation in the selected schema; public supplies pgvector only.
    PERFORM set_config('search_path', format('%I, public', target_schema), true);
    PERFORM pg_advisory_xact_lock(hashtext(current_database()), hashtext(target_schema || ':rag_schema'));
    CREATE TABLE IF NOT EXISTS rag_schema_migrations (
        version TEXT PRIMARY KEY,
        applied_at TIMESTAMPTZ NOT NULL DEFAULT now()
    );
    IF EXISTS (SELECT 1 FROM rag_schema_migrations WHERE version = '002_create_rag_schema') THEN
        RAISE NOTICE '002_create_rag_schema already applied; skipping';
        RETURN;
    END IF;
    -- Do not hide partial/manual installations behind CREATE TABLE IF NOT EXISTS.
    FOREACH object_name IN ARRAY ARRAY['documents', 'document_versions', 'document_chunks', 'chunk_embeddings'] LOOP
        IF to_regclass(format('%I.%I', target_schema, object_name)) IS NOT NULL THEN
            RAISE EXCEPTION 'Unexpected existing RAG object %.%; inspect schema before applying migration', target_schema, object_name;
        END IF;
    END LOOP;

    CREATE TABLE documents (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        tenant_id TEXT NOT NULL CHECK (tenant_id <> '' AND tenant_id !~ '^[[:space:]]|[[:space:]]$'),
        document_id TEXT NOT NULL CHECK (document_id <> '' AND document_id !~ '^[[:space:]]|[[:space:]]$'),
        created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
        CONSTRAINT uq_documents_tenant_document UNIQUE (tenant_id, document_id)
    );

    -- Ownership/identity changes require an explicit future migration, not an
    -- accidental UPDATE that silently reassigns all descendant content.
    CREATE FUNCTION protect_document_identity() RETURNS TRIGGER
    LANGUAGE plpgsql AS $identity$
    BEGIN
        IF NEW.tenant_id IS DISTINCT FROM OLD.tenant_id
           OR NEW.document_id IS DISTINCT FROM OLD.document_id THEN
            RAISE EXCEPTION 'Document tenant and external identity are immutable'
                USING ERRCODE = '23514';
        END IF;
        RETURN NEW;
    END
    $identity$;
    CREATE TRIGGER documents_identity_immutable
        BEFORE UPDATE OF tenant_id, document_id ON documents
        FOR EACH ROW EXECUTE FUNCTION protect_document_identity();

    CREATE TABLE document_versions (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        document_fk BIGINT NOT NULL REFERENCES documents(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
        version TEXT NOT NULL CHECK (version ~ '[^[:space:]]'),
        title TEXT NOT NULL CHECK (title ~ '[^[:space:]]'),
        effective_date DATE NOT NULL CHECK (isfinite(effective_date)),
        status TEXT NOT NULL CHECK (status IN ('active', 'archived')),
        visibility TEXT NOT NULL CHECK (visibility IN ('public', 'internal')),
        source_sha256 TEXT NOT NULL CHECK (source_sha256 ~ '^[0-9a-f]{64}$'),
        source_path TEXT NOT NULL CHECK (source_path ~ '[^[:space:]]'),
        source_format TEXT NOT NULL CHECK (source_format IN ('pdf', 'html', 'md', 'txt')),
        synthetic BOOLEAN NOT NULL,
        topic_family TEXT NOT NULL CHECK (topic_family ~ '[^[:space:]]'),
        word_count INTEGER NOT NULL CHECK (word_count >= 0),
        pdf_pages INTEGER CHECK (pdf_pages > 0),
        section_count INTEGER NOT NULL CHECK (section_count >= 0),
        scope_note TEXT NOT NULL CHECK (scope_note ~ '[^[:space:]]'),
        created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
        CONSTRAINT uq_document_versions_document_version UNIQUE (document_fk, version),
        CONSTRAINT ck_document_versions_pdf_pages CHECK (source_format = 'pdf' OR pdf_pages IS NULL)
    );
    -- Archive the previous version before activating its replacement in a transaction.
    CREATE UNIQUE INDEX uq_document_versions_one_active
        ON document_versions (document_fk) WHERE status = 'active';

    CREATE TABLE document_chunks (
        chunk_id TEXT PRIMARY KEY CHECK (chunk_id ~ '^chk_[0-9a-f]{64}$'),
        document_version_fk BIGINT NOT NULL REFERENCES document_versions(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
        chunk_index INTEGER NOT NULL CHECK (chunk_index >= 0),
        text TEXT NOT NULL CHECK (text ~ '[^[:space:]]'),
        token_count INTEGER NOT NULL CHECK (token_count > 0),
        heading_path TEXT[] NOT NULL CHECK (array_position(heading_path, NULL) IS NULL),
        start_page INTEGER,
        end_page INTEGER,
        source_block_ids INTEGER[] NOT NULL,
        tokenizer_name TEXT NOT NULL CHECK (tokenizer_name ~ '[^[:space:]]'),
        tokenizer_version TEXT NOT NULL CHECK (tokenizer_version ~ '[^[:space:]]'),
        chunking_config_version TEXT NOT NULL CHECK (chunking_config_version ~ '[^[:space:]]'),
        chunking_configuration JSONB NOT NULL CHECK (jsonb_typeof(chunking_configuration) = 'object'),
        chunking_config_fingerprint TEXT NOT NULL CHECK (chunking_config_fingerprint ~ '^[0-9a-f]{64}$'),
        created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
        CONSTRAINT uq_document_chunks_version_config_index UNIQUE (document_version_fk, chunking_config_fingerprint, chunk_index),
        CONSTRAINT ck_document_chunks_pages CHECK (
            (start_page IS NULL AND end_page IS NULL) OR
            (start_page IS NOT NULL AND end_page IS NOT NULL AND start_page > 0 AND end_page >= start_page)
        ),
        CONSTRAINT ck_document_chunks_source_blocks CHECK (
            cardinality(source_block_ids) > 0 AND array_ndims(source_block_ids) = 1
            AND array_position(source_block_ids, NULL) IS NULL AND 0 <= ALL(source_block_ids)
        ),
        CONSTRAINT ck_document_chunks_heading_dimensions CHECK (
            cardinality(heading_path) = 0 OR array_ndims(heading_path) = 1
        )
    );

    CREATE TABLE chunk_embeddings (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        chunk_id TEXT NOT NULL REFERENCES document_chunks(chunk_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
        embedding public.vector(384) NOT NULL CHECK (public.vector_norm(embedding) > 0),
        embedding_model_id TEXT NOT NULL CHECK (embedding_model_id ~ '[^[:space:]]'),
        embedding_model_revision TEXT NOT NULL CHECK (embedding_model_revision ~ '^[0-9a-f]{40}$'),
        embedding_config_fingerprint TEXT NOT NULL CHECK (embedding_config_fingerprint ~ '^[0-9a-f]{64}$'),
        input_fingerprint TEXT NOT NULL CHECK (input_fingerprint ~ '^emb_[0-9a-f]{64}$'),
        document_instruction TEXT NOT NULL,
        query_instruction TEXT NOT NULL,
        normalize_embeddings BOOLEAN NOT NULL,
        encoding_config_version TEXT NOT NULL CHECK (encoding_config_version ~ '[^[:space:]]'),
        created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
        CONSTRAINT uq_chunk_embeddings_identity UNIQUE (
            chunk_id, embedding_model_id, embedding_model_revision, embedding_config_fingerprint
        )
    );

    COMMENT ON TABLE documents IS 'Immutable tenant-scoped logical document identity; authorization remains an application responsibility.';
    COMMENT ON TABLE document_versions IS 'Version-specific source metadata; archived history is retained.';
    COMMENT ON TABLE document_chunks IS 'Phase 4 stable chunks and provenance; configuration fingerprints are verified by ingestion.';
    COMMENT ON TABLE chunk_embeddings IS '384-dimensional document vectors; select one model/revision/configuration for retrieval.';
    INSERT INTO rag_schema_migrations (version) VALUES ('002_create_rag_schema');
END
$migration$;
